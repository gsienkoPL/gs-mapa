_BY_TERYT: Dict[str, Tuple[str, str, str]] = {p[0]: p for p in POWIATY}


def powiat(teryt: str) -> Optional[Tuple[str, str, str]]:
    """Powiat o kodzie TERYT (4 cyfry) albo ``None``."""
    return _BY_TERYT.get((teryt or "").strip())


def powiat_label(teryt: str) -> str:
    """Etykieta powiatu, np. ``powiat krakowski (małopolskie)``, ``m. Lublin (lubelskie)``."""
    found = powiat(teryt)
    if found is None:
        return f"powiat {teryt}"
    _, name, voivodeship = found
    return f"{name if name.startswith('m. ') else 'powiat ' + name} ({voivodeship})"


def search_powiaty(text: str) -> List[Tuple[str, str, str]]:
    """Powiaty pasujące do tekstu: prefiks TERYT albo fragment nazwy (bez polskich znaków)."""
    query = normalize_text(text)
    if not query:
        return list(POWIATY)
    if query.isdigit():
        return [p for p in POWIATY if p[0].startswith(query)]
    return [p for p in POWIATY if query in normalize_text(f"{p[1]} {p[2]}")]
